// Writes assets/landmarks/sites.json: the real footprints, heights, terrain,
// and bridge decks of the beltline-eastside landmarks, in local meters around
// each landmark origin, for scripts/blender/landmarks.py. Uses the same pure
// level code as the game (landmarks.js, terrain.js, bridges.js), so a model
// built from this file fits where the game puts the building or deck.
//   node scripts/assets/landmark-sites.mjs
import fs from "node:fs";
import { landmarkPlacements } from "../../src/level/geo/landmarks.js";
import { buildingSpan, terrainOf, bridgeDeck, BRIDGE } from "../../src/level/geo/terrain.js";
import { bridgeLayout, densify, slicePolyline } from "../../src/level/geo/bridges.js";

const LEVEL = "levels/beltline-eastside/level.json";
const level = JSON.parse(fs.readFileSync(LEVEL, "utf8"));
const t = terrainOf(level);
const r2 = (v) => Math.round(v * 100) / 100;

const BUILDINGS = [
  { key: "ponce-city-market", name: "Ponce City Market" },
  { key: "telephone-factory-lofts", name: "Telephone Factory Lofts" },
  { key: "studioplex", name: "Studioplex" },
  { key: "new-realm-brewing", name: "New Realm Brewing" },
];

// Trail bridges and the Freedom Parkway overpass group (OSM way ids).
const BRIDGES = [
  { key: "bridge-north-ave", title: "Eastside Trail over North Avenue", style: "trail", ids: ["w741961708", "w83294497"] },
  { key: "bridge-ralph-mcgill", title: "Eastside Trail over Ralph McGill Boulevard", style: "trail", ids: ["w83291376"] },
  { key: "bridge-ponce", title: "Eastside Trail over Ponce de Leon Avenue (south half, the level ends at z = -972.96)", style: "trail", ids: ["w83291379"] },
  { key: "bridge-freedom-parkway", title: "John Lewis Freedom Parkway and Stone Mountain Trail over the Eastside Trail", style: "road", ids: ["w156324719", "w156324725", "w29094065", "w29094070", "w44851092"] },
];

function bbox(points) {
  const b = { minX: Infinity, maxX: -Infinity, minZ: Infinity, maxZ: -Infinity };
  for (const [x, z] of points) {
    b.minX = Math.min(b.minX, x);
    b.maxX = Math.max(b.maxX, x);
    b.minZ = Math.min(b.minZ, z);
    b.maxZ = Math.max(b.maxZ, z);
  }
  return b;
}

// Terrain heights on a grid around a box, local to the origin.
function terrainGrid(b, origin, step = 2, pad = 6) {
  const x0 = Math.floor(b.minX - pad);
  const z0 = Math.floor(b.minZ - pad);
  const cols = Math.ceil((b.maxX - b.minX + 2 * pad) / step) + 1;
  const rows = Math.ceil((b.maxZ - b.minZ + 2 * pad) / step) + 1;
  const h = [];
  for (let r = 0; r < rows; r += 1) for (let c = 0; c < cols; c += 1) h.push(r2(t.height(x0 + c * step, z0 + r * step) - origin[1]));
  return { x0: r2(x0 - origin[0]), z0: r2(z0 - origin[2]), step, cols, rows, h };
}

const placements = landmarkPlacements(level);
const out = {
  about: "Generated by scripts/assets/landmark-sites.mjs from " + LEVEL + ". Axes as the level: +x east, +y up, +z south, meters. Every point is local to its origin; the placement transform is { position: origin, yaw: 0 }.",
  level: level.name,
  bounds: level.bounds,
  attribution: level.attribution,
  buildings: {},
  bridges: {},
  bridgeConst: BRIDGE,
};

for (const { key, name } of BUILDINGS) {
  const b = level.buildings.find((x) => x.name === name);
  const span = buildingSpan(level, b);
  const bb = bbox(b.outer);
  const origin = [r2((bb.minX + bb.maxX) / 2), r2(span.ground), r2((bb.minZ + bb.maxZ) / 2)];
  const loc = (ring) => ring.map(([x, z]) => [r2(x - origin[0]), r2(z - origin[2])]);
  const entry = {
    osm: b.id,
    name,
    type: b.type ?? null,
    height: b.height,
    heightSource: b.heightSource,
    origin,
    base: r2(span.base - span.ground),
    top: r2(span.top - span.ground),
    size: [r2(bb.maxX - bb.minX), r2(bb.maxZ - bb.minZ)],
    outer: loc(b.outer),
    holes: (b.holes ?? []).map(loc),
    terrain: terrainGrid(bb, origin),
  };
  // The direction (unit [x, z]) and distance to the nearest Eastside Trail
  // point, so the generator can turn the signs and the deck to the trail.
  let near = null;
  for (const st of level.strips) {
    if (st.kind !== "trail") continue;
    for (const [x, z] of densify(st.points, 2)) {
      const d = Math.hypot(x - origin[0], z - origin[2]);
      if (!near || d < near.d) near = { d, x, z };
    }
  }
  entry.trail = { distance: r2(near.d), dir: [r2((near.x - origin[0]) / near.d), r2((near.z - origin[2]) / near.d)] };
  const p = placements.find((q) => q.building === b.id);
  if (p) {
    entry.anchor = [r2(p.model.x - origin[0]), r2(p.model.y - origin[1]), r2(p.model.z - origin[2])];
    if (p.sign) entry.sign = { at: [r2(p.sign.x - origin[0]), r2(p.sign.y - origin[1]), r2(p.sign.z - origin[2])], yaw: p.sign.yaw, width: p.sign.width, height: p.sign.height };
  }
  out.buildings[key] = entry;
}

for (const g of BRIDGES) {
  const strips = g.ids.map((id) => level.strips.find((s) => s.id === id));
  const all = strips.flatMap((s) => s.points);
  const bb = bbox(all);
  const decks = [];
  for (const s of strips) {
    const L = bridgeLayout(level, s);
    const deck = bridgeDeck(level, s);
    const pts = densify(slicePolyline(L.points, L.span[0], L.span[1]), 1);
    decks.push({ osm: s.id, name: s.name ?? null, highway: s.highway, width: s.width, host: L.host, points: pts.map(([x, z]) => [x, z, deck(x, z), t.height(x, z)]) });
  }
  const origin = [r2((bb.minX + bb.maxX) / 2), r2(Math.min(...decks.flatMap((d) => d.points.map((p) => p[2])))), r2((bb.minZ + bb.maxZ) / 2)];
  for (const d of decks) d.points = d.points.map(([x, z, y, gy]) => [r2(x - origin[0]), r2(y - origin[1]), r2(z - origin[2]), r2(gy - origin[1])]);
  out.bridges[g.key] = { title: g.title, style: g.style, origin, decks, terrain: terrainGrid(bb, origin, 2, 14) };
}

fs.writeFileSync("assets/landmarks/sites.json", JSON.stringify(out));
for (const [k, v] of Object.entries(out.buildings)) console.log(k, "origin", v.origin, "base", v.base, "top", v.top, "trail", JSON.stringify(v.trail), "anchor", v.anchor ?? "", v.sign ? "sign " + JSON.stringify(v.sign) : "");
for (const [k, v] of Object.entries(out.bridges)) console.log(k, "origin", v.origin, v.decks.map((d) => `${d.osm} w${d.width} n${d.points.length} host ${d.host}`).join("; "));
