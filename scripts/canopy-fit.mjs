// Makes src/sim/canopy-fit.js: the crown ellipsoid of the follow camera for
// each tree species and variant (#230).
//
//   node scripts/canopy-fit.mjs
//
// A crown volume must hold both tree meshes of a variant: the procedural
// tree of the toon look (src/level/geo/trees.js, puffs and leaf cards) and
// the Blender GLB tree of the pbr look (assets/trees/<species>.glb). The GLB
// files use Draco, so the script reads them in headless Chromium through the
// Vite dev server, with the same loader as the game. fitCrown()
// (src/sim/camera.js) fits the ellipsoid to the points at or over the crown
// bottom: the lower of the species `clear` height and the lowest GLB leaf.
// Run it again after a change to the tree meshes or the species table.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";
import { createServer } from "vite";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PORT = Number(process.env.FIT_PORT ?? 5191);

const server = await createServer({ root: ROOT, server: { port: PORT, strictPort: true, hmr: false }, logLevel: "warn" });
await server.listen();
const browser = await chromium.launch({ args: ["--no-sandbox", "--enable-unsafe-swiftshader", "--disable-dev-shm-usage"] });
try {
  const page = await browser.newPage();
  await page.goto(`http://localhost:${PORT}/src/sim/canopy-fit.js`);
  const fit = await page.evaluate(async () => {
    const view = await import("/src/render/geo-view.js");
    const { fitCrown } = await import("/src/sim/camera.js");
    const trees = await import("/src/level/geo/trees.js");
    const round = (v) => Math.ceil(v * 100) / 100;
    const out = {};
    for (const species of Object.keys(trees.TREE_SPECIES)) {
      const glb = await view.loadKitTemplates(view.TREE_GLB_URLS[species]);
      out[species] = [];
      for (let variant = 0; variant < trees.TREE_VARIANTS; variant += 1) {
        const meshes = [false, true].map((cards) => trees.treeTemplate(species, variant, 0, "summer", { cards }).positions);
        let bottom = trees.TREE_SPECIES[species].clear;
        const g = glb[`tree_${species}_${variant}`];
        if (g) {
          meshes.push(g.positions);
          for (let i = 0; i < g.positions.length / 3; i += 1) if (g.leaf && g.leaf[i * 3 + 2] >= 0) bottom = Math.min(bottom, g.positions[i * 3 + 1]);
        }
        const f = fitCrown(meshes, bottom);
        out[species].push({ y: Math.round(f.y * 100) / 100, h: round(f.h), reach: round(f.reach), glb: Boolean(g) });
      }
    }
    return out;
  });
  const lines = Object.entries(fit).map(([species, rows]) => `  ${species}: [\n${rows.map((r) => `    { y: ${r.y}, h: ${r.h}, reach: ${r.reach} },${r.glb ? "" : " // no GLB tree"}`).join("\n")}\n  ],`);
  const text = `// Generated by scripts/canopy-fit.mjs. Do not edit by hand.
//
// The crown ellipsoid of the follow camera for each tree species and
// variant (src/sim/camera.js treeVolume), at placement scale 1: the center
// height \`y\`, the half height \`h\` and the radius \`reach\`, in m. It holds
// the procedural tree and the GLB tree of the variant.
export const CANOPY_FIT = {
${lines.join("\n")}
};
`;
  writeFileSync(resolve(ROOT, "src/sim/canopy-fit.js"), text);
  console.log(text);
} finally {
  await browser.close();
  await server.close();
}
